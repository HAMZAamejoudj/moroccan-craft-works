export function getProductBySlug(slug: string): CatalogProduct | undefined {
  const normalized = (slug || '').toLowerCase().trim()
  return CATALOG_PRODUCTS.find((p) => {
    const pSlug = (p.slug || '').toLowerCase().trim()
    const pId = (p.id || '').toLowerCase().trim()
    return pSlug === normalized || pId === normalized
  })
}

export function getProductById(id: string): CatalogProduct | undefined {
  return CATALOG_PRODUCTS.find((p) => p.id === id)
}

export function getRelatedProducts(product: CatalogProduct, limit = 4): CatalogProduct[] {
  return CATALOG_PRODUCTS.filter(
    (p) => (p.slug || p.id) !== (product.slug || product.id) && (p.categoryId === product.categoryId || p.category === product.category)
  ).slice(0, limit)
}
